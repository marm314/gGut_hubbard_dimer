"""Ng=2 analogue of plot_ng4_dV2_confirmed.py: generates eqp_vs_U.png and E_vs_U.png for
scan_ng2_dV2_confirmed/ -- purely from already-saved data (that directory's own
lowest_energy.txt, plus each original scan's own branch output.out for the comparison
lines), no gga_dimer.py/not_imp_gga_dimer.py re-runs.

The 3D ridgeline (eqp_vs_U_3d.png) and spectral-function video (A_omega_vs_U.mp4) for this
same directory are generated by plot_eqp_3d_dV2.py / make_A_omega_video_dV2.py instead.
"""
import os
import re
import sys

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "scan_ed_deltaV"))
import make_plot as ed_dV  # scan_ed_deltaV/make_plot.py

Ng, t, deltaV = 2, 1.0, 2.0
CONF_DIR = "scan_ng2_dV2_confirmed"
IMP_DIR = "scan_ng2_imp_dV2"
NOTIMP_DIR = "scan_ng2_not_imp_dV2"

PAIR_COLORS = ["tab:orange", "tab:blue"]
GHOST_COLOR = "0.6"


def branch_color(i, n):
    pair = min(i, n - 1 - i)
    return PAIR_COLORS[pair] if pair < len(PAIR_COLORS) else GHOST_COLOR


def ed_poles(Us):
    """deltaV_ed = 2*deltaV -- see scan_ng2_not_imp_dV2_U.py's ed_ground_state_energy
    docstring for why exact_dimer_deltaV.py's deltaV is not the same parameter."""
    return np.array([sorted(ed_dV.analytic_poles(t, U, 2.0 * deltaV)[0]) for U in Us])


def load_branch_map(scan_dir):
    br = {}
    for line in open(os.path.join(scan_dir, "lowest_energy.txt")):
        if not line.startswith("#") and line.strip():
            p = line.split()
            br[round(float(p[0]), 1)] = p[2]
    return br


if __name__ == "__main__":
    rows = []
    for line in open(os.path.join(CONF_DIR, "lowest_energy.txt")):
        if line.startswith("#") or not line.strip():
            continue
        p = line.split()
        U = round(float(p[0]), 1)
        E = float(p[1])
        eqp = np.array([float(x) for x in p[2:]])
        rows.append((U, E, eqp))
    Us = np.array([r[0] for r in rows])
    E_conf = np.array([r[1] for r in rows])
    eq = np.array([r[2] for r in rows])

    # --- eqp_vs_U.png ---
    ed_p = ed_poles(Us)
    n = eq.shape[1]
    plt.figure(figsize=(6.4, 4.8))
    for i in range(n):
        plt.plot(Us, eq[:, i], "-", lw=1.2, color=branch_color(i, n))
    for i in range(ed_p.shape[1]):
        plt.plot(Us, ed_p[:, i], "--", lw=1.2, color="black",
                  label="exact (ED)" if i == 0 else None)
    plt.axhline(0.0, color="gray", lw=0.5, ls=":")
    plt.xlabel("U/t"); plt.ylabel("quasiparticle energy / t")
    plt.title(f"Quasiparticle energies, cross-checked mutual solution (Ng={Ng}, $\\Delta V/t={deltaV:g}$)")
    plt.legend(fontsize=8)
    plt.tight_layout(); plt.savefig(os.path.join(CONF_DIR, "eqp_vs_U.png"), dpi=150); plt.close()

    # --- E_vs_U.png: confirmed mutual solution vs each solver's OWN native scan vs ED ---
    br_imp = load_branch_map(IMP_DIR)
    br_ni = load_branch_map(NOTIMP_DIR)
    E_imp, E_ni = [], []
    for U in Us:
        txt_imp = open(os.path.join(IMP_DIR, br_imp[U], f"U_{U:.1f}", "output.out")).read()
        E_imp.append(float(re.search(r"E_var/t=(-?[\d.]+)", txt_imp).group(1)))
        txt_ni = open(os.path.join(NOTIMP_DIR, br_ni[U], f"U_{U:.1f}", "output.out")).read()
        E_ni.append(float(re.search(r"E_var/t=(-?[\d.]+)", txt_ni).group(1)))
    E_imp = np.array(E_imp)
    E_ni = np.array(E_ni)
    E_ed = np.array([ed_dV.E0_explicit(t, U, 2.0 * deltaV) for U in Us])

    fig, ax = plt.subplots(2, 1, figsize=(6.4, 6.2), sharex=True, gridspec_kw=dict(height_ratios=[3, 1.4]))
    ax[0].plot(Us, E_imp, ":", lw=1.1, color="tab:blue", label="gga_dimer.py's own (scan_ng2_imp_dV2)")
    ax[0].plot(Us, E_ni, ":", lw=1.1, color="tab:brown", label="not_imp_gga_dimer.py's own (scan_ng2_not_imp_dV2)")
    ax[0].plot(Us, E_conf, "-", lw=1.8, color="black", label="confirmed mutual solution")
    ax[0].plot(Us, E_ed, "--", lw=1.4, color="black", label="exact (ED)")
    ax[0].set_ylabel("E_var / t")
    ax[0].set_title(f"Variational energy vs U, cross-checked (Ng={Ng}, $\\Delta V/t={deltaV:g}$)")
    ax[0].legend(fontsize=8)
    ax[1].plot(Us, E_imp - E_conf, "-", lw=1.2, color="tab:blue", label="imp-own excess")
    ax[1].plot(Us, E_ni - E_conf, "-", lw=1.2, color="tab:brown", label="notimp-own excess")
    ax[1].axhline(0.0, color="gray", lw=0.5, ls=":")
    ax[1].set_xlabel("U/t"); ax[1].set_ylabel("energy excess vs confirmed"); ax[1].legend(fontsize=7)
    plt.tight_layout(); plt.savefig(os.path.join(CONF_DIR, "E_vs_U.png"), dpi=150); plt.close()

    print(f"max imp-own excess    = {(E_imp - E_conf).max():.3e}")
    print(f"max notimp-own excess = {(E_ni - E_conf).max():.3e}")
    print(f"wrote {CONF_DIR}/eqp_vs_U.png and {CONF_DIR}/E_vs_U.png")
